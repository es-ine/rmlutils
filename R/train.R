#' @rdname train
#' @export
train.LGBModeler <- function(object, data, subSet = NULL) {

  #Validate target, subSet and filter data
  RMLutils:::.validate_target(object = object, data = data)
  data <- RMLutils:::.validate_generic_data_subset(data = data,
                                        subSet = subSet,
                                        target = getTarget(object))

  if(!is.null(object$params$weight_column)){
    weights_values <- data[subSet, get(object$params$weight_column)]
  }else{
    weights_values <- rep(1, nrow(data[subSet]))
  }
  #Filter regressors before finding categorical variables
  if(class(object)[3] == "classifierModeler"){
    #Get levels of target variable
    t.levels <- levels(data[[object$target]])
    #Assign direct levels to class_names
    object$class_names <- t.levels
    if(object$params$objective == "binary"){
      if(length(t.levels)!=2){
        stop("Target variable is not binary. Please review your data.")
      }
      #Check if positive_class was provided
      if(!is.null(object$positive_class)){
        if((!object$positive_class %in% t.levels)){
          stop("The provided positive_class was not found in the data, please review your inputs.")
        }
        #Map negative and positive class to their actual indexing in LightGBM
        #0 is negative and 1 is positive
        negative_class <- t.levels[t.levels != object$positive_class]
        t.levels_mapping <- 0:1
        names(t.levels_mapping) <- c(negative_class, object$positive_class)
        data[,(object$target) := t.levels_mapping[as.character(get(object$target))]]
        #data2 <- copy(data)
        #data2[,new_target := t.levels_mapping[as.character(get(object$target))]]
      }else{#If it was not provided, throw warning
        warning("positive_class was not set when defining the modeler. Assuming first category to be the negative one and last category to be the positive one.")
        #Proceed with ordinal encoding (and substracting 1 to make it work with LightGBM)
        data[,(object$target) := as.numeric(get(object$target)) - 1]
      }
    }else{#If objective is multiclass:
      #If objective is not binary and positive_class was provided, throw warning
      if(!is.null(object$positive_class)){
        warning("A positive_class was provided, but objective is different from binary. This parameter will be unused.")
      }

      #Proceed with ordinal encoding (and substracting 1 to make it work with LightGBM)
      data[,(object$target) := as.numeric(get(object$target)) - 1]
    }


    targ <- data.matrix(data[, object$target, with= FALSE])
  }else{
    targ <- data.matrix(data[, object$target, with= FALSE])
  }

  data <- data[, object$regressors, with=FALSE]

  #Automatically find categorical variables
  is.fact <- sapply(data, is.factor)
  if(sum(is.fact) > 0){
    ifCategVars <- TRUE
    categVars <- names(is.fact)[is.fact]
    #If the target variable is categorical, save its levels in the modeler object
    #if(object$target %in% names(is.fact)){
    #  object$class_names <- levels(data[[object$target]])
    #  data[, object$target := as.integer(get(object$target)) - 1]
    #  categVars <- categVars[!categVars %in% c(object$target)]
    #}
    #Then, convert categorical columns into integer, starting from 0 (necessary for lightgbm)
    data[, (categVars) := lapply(.SD, function(x) as.integer(x) - 1), .SDcols = categVars]
  }else{
    ifCategVars <- FALSE
  }

  data.mat <- data.matrix(data)

  if(ifCategVars){
    lgb.dy1 <- lightgbm::lgb.Dataset(data = data.mat,#[, colnames(data.mat) != object$target, drop = F],
                                     label = targ,
                                     weight = weights_values,
                                     categorical_feature = categVars)
  }else{
    lgb.dy1 <- lightgbm::lgb.Dataset(data = data.mat,#[, colnames(data.mat) != object$target, drop = F],
                                     label = targ,
                                     weight = weights_values)
  }
  #Clean model in case there was a trained model previously
  object <- modelClean(object)

  object$trainedModel <- lightgbm::lgb.train(data = lgb.dy1,
                                              nrounds = object$params$nrounds,
                                              params = object$params)
  #Set boolean trained flag
  object$isTrained <- TRUE
  return(object)
}

#' @rdname train
#' @export
train.rangerModeler <- function(object, data, subSet = NULL) {

  #Validate target, subSet and filter data
  RMLutils:::.validate_target(object = object, data = data)
  data <- RMLutils:::.validate_generic_data_subset(data = data,
                                        subSet = subSet,
                                        target = getTarget(object))

  #Check whether the target variable is categorical type and automatically set the classification parameter
  if(is.factor(data[[object$target]])){
    object$params$classification <- TRUE
    object$params$probability <- TRUE#This forces the model to return probabilities when using predict()
    object$class_names <- levels(data[[object$target]])
  }else{
    object$params$classification <- FALSE
  }


  #if(!is.null(object$params$weight_column)){
  if(!is.null(object$params$case.weights)){
    weights_values <- data[, get(object$params$case.weights)]
  }else{
    weights_values <- rep(1, nrow(data))
  }

  # Se limpia modelo entrenado en caso de que haya
  object <- modelClean(object)

  parametros <- object$params
  parametros$case.weights <- weights_values
  parametros$model_name <- NULL
  parametros$target <- NULL
  parametros$data <- data
  parametros$formula <- formula(eval(parse(text=paste0(paste0(object$target, "~"),paste0(object$regressors, collapse = "+")))))
  object$trainedModel <- do.call(ranger::ranger, args = parametros )

  #Set boolean trained flag
  object$isTrained <- TRUE
  return(object)
}

#' @rdname train
#' @export
train.catboostModeler <- function(object, data, subSet = NULL) {

  #Assign validation data (if it exists)
  val_data <- object$val_data

  #Validate target, subSet and filter data
  RMLutils:::.validate_target(object = object, data = data)
  data <- RMLutils:::.validate_generic_data_subset(data = data,
                                        subSet = subSet,
                                        target = getTarget(object))

  regressors.dt <- data[, object$regressors, with=FALSE]
  #TODO: Re-level target to make sure negative and positive classes are
  #properly assigned.

  if(class(object)[3] == "classifierModeler"){#Classification
    #Get levels of target variable
    t.levels <- levels(data[[object$target]])
    #Assign direct levels to class_names
    object$class_names <- t.levels
    if(object$params$loss_function %in% c("Logloss","CrossEntropy")){#Binary
      if(length(t.levels)!=2){
        stop("Target variable is not binary. Please review your data.")
      }
      #Check if positive_class was provided
      if(!is.null(object$positive_class)){
        if((!object$positive_class %in% t.levels)){
          stop("The provided positive_class was not found in the data, please review your inputs.")
        }
        #Find negative class
        negative_class <- t.levels[t.levels != object$positive_class]

        #Re-level target variable factor levels so that the first one is the
        #negative class and the last one, the positive one
        #The same will be done for the validation set
        target <- data[, get(object$target)]
        target <- factor(target, levels = c(negative_class, object$positive_class))

      }else{#If it was not provided, throw warning
        warning("positive_class was not set when defining the modeler. Assuming first category to be the negative one and last category to be the positive one.")
        target <- data[, get(object$target)]
      }
    }else{#Multiclass
      target <- data[, get(object$target)]
    }
  }else{#Regression
    target <- data[, get(object$target)]
  }

  if(!is.null(object$params$weight_column)){
    weights_values <- data[, get(object$params$weight_column)]
  }else{
    weights_values <- rep(1, nrow(data))
  }

  pool_train <- catboost::catboost.load_pool(regressors.dt,
                                  label = target,
                                  weight = weights_values)
  if(!is.null(val_data)){
    val_data <- as.data.table(val_data)#Force conversion just in case
    if(!is.null(object$params$weight_column)){
      val_weights_values <- val_data[, get(object$params$weight_column)]
    }else{
      val_weights_values <- rep(1, nrow(val_data))
    }
    val_regressors.dt <- val_data[subSet, object$regressors, with=FALSE]
    #If it's a binary classification target and object$positive_class is not null
    if(object$params$loss_function %in% c("Logloss","CrossEntropy") & !is.null(object$positive_class)){
      val_target <- val_data[, get(object$target)]
      val_target <- factor(val_target, levels = c(negative_class, object$positive_class))
    }else{
      val_target <- val_data[, get(object$target)]
    }

    pool_val <-  catboost::catboost.load_pool(val_regressors.dt,
                                    label = val_target,
                                    weight = val_weights_values)
  }else{
    pool_val <- NULL
  }

  # Se limpia modelo entrenado en caso de que haya
  object <- modelClean(object)

  #Considerar si añadir validación al entrenamiento (el modelo lo permite)
  object$trainedModel <- catboost::catboost.train(learn_pool = pool_train,
                                                  test_pool = pool_val,
                                                  params = object$params)
  #Set boolean trained flag
  object$isTrained <- TRUE
  return(object)
}


#' @rdname train
#' @export
train.miceModeler <- function(object, data, subSet = NULL) {

  #Validate target, subSet and filter data
  RMLutils:::.validate_target(object = object, data = data)
  data <- RMLutils:::.validate_generic_data_subset(data = data,
                                        subSet = subSet,
                                        target = getTarget(object))

  #Check whether the target variable is categorical type and assign class_names if so
  if(is.factor(data[[object$target]])){
    object$class_names <- levels(data[[object$target]])
  }

  # Clean trainedModel if it exists and assign new data as trained model
  object <- modelClean(object)
  object$trainedModel <- copy(data)

  #This assumes that there are no more columns besides target and regressors
  #Note that if there is a weightsColumn this may cause issues
  if(is.null(object$regressors)){
    warning("No regressors were defined, assuming all variables besides target are regressors.")
    object$regressors <- setdiff(colnames(object$trainedModel), object$target)
  }

  object$tipo_target <- class(object$trainedModel[, get(object$target)])

  #Set boolean trained flag
  object$isTrained <- TRUE
  return(object)
}

#' @rdname train
#' @export
train.prePredModeler <- function(object, data, subSet = NULL) {

  data <- RMLutils:::.validate_generic_data_subset(data = data,
                                        subSet = subSet)

  # Get initial models predictions
  object$predModeler <- RMLutils::train(object = object$predModeler, data = data)
  preds <- RMLutils::getPredictions(object$predModeler, data)
  # Add predictions to data copy
  dataCopy <- as.data.table(data)
  dataCopy[, colnames(preds) := as.data.table(preds)]
  # Train main model
  object$mainModeler <- RMLutils::train(object$mainModeler, dataCopy)
  # Remove data copy
  rm(dataCopy)
  #Set boolean trained flag
  object$isTrained <- TRUE
  return(object)
}

#' @rdname train
#' @export
train.classifRegModeler <- function(object, data, subSet = NULL) {

  RMLutils:::.validate_target(object = object, data = data)
  data <- RMLutils:::.validate_generic_data_subset(data = data,
                                        subSet = subSet,
                                        target = getTarget(object))
  # train the classification model
  #Data is already filtered here
  classifSubset <- 1:nrow(data)

  object <- modelClean(object)
  target <- as.matrix(data[[object$target]])[,1]

  if (object$epsilon == 0) {
    data[[paste0(object$target,"CAT")]] <- factor(
      ifelse(target %in% object$specialCats,
             target,
             "NOSP"),
      levels = c(object$specialCats, "NOSP")
    )
  } else {
    data[[paste0(object$target,"CAT")]] <- factor(
      sapply(lapply(target, function(y) abs(y - object$specialCats)), function(dif){
        ifelse(any(dif < object$epsilon),
               object$specialCats[which(dif < object$epsilon)],
               "NOSP")}),
      levels = c(object$specialCats, "NOSP")
    )
  }

  object$classifModeler <- setTarget(object$classifModeler, paste0(object$target,"CAT"))
  object$classifModeler <- RMLutils::train(object$classifModeler, data, classifSubset)

  # select the non special elements of the training data
  regSubset <- classifSubset[which(
    as.matrix(data[[paste0(object$target,"CAT")]])[classifSubset, 1] == "NOSP")]
  object$trainedModel <- list()

  data[, paste0(object$target,"CAT") := NULL]

  # train the regression model
  if (length(regSubset) > object$minRows) {
    object$regModeler <- RMLutils::train(object$regModeler, data, regSubset)
  } else {
    if (inherits(data,"H2OFrame")) {
      object$trainedModel$nonCatsMean <- h2o.mean(data[regSubset, object$target])
    } else {
      object$trainedModel$nonCatsMean <- mean(data[[object$target]][regSubset])
    }
  }
  #Set boolean trained flag
  object$isTrained <- TRUE
  return(object)
}


#' @rdname train
#' @export
train.memoryModeler <- function(object, data, subSet = NULL) {
  #Check if current data and previous data have the same columns
  if(!all(colnames(data) %in% colnames(data.table::rbindlist(object$data, fill = TRUE)))){
    stop(paste0("Current training data structure does not match the memoryModeler internal data structure.\n ",
                "Current training data columns: ", paste0(colnames(data), collapse = ", "),
                "\n ",
                "MemoryModeler data columns: ", paste0(colnames(data.table::rbindlist(object$data, fill = TRUE)))))
  }
  object$modeler <- train(object$modeler,
                          data.table::rbindlist(append(list(data), object$data), fill = FALSE),
                          subSet)
  #Set boolean trained flag
  object$isTrained <- TRUE
  return(object)
}
