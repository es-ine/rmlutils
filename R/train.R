  return(object)
}
#' @rdname train
#' @import data.table
#' @export
train.HTModeler <- function(object, data, subSet = NULL) {
  target <- getTarget(object)
  weightsColumn <- object$weightsColumn

  #Validate target, subSet and filter data
  RMLutils:::.validate_target(object = object, data = data)
  data <- RMLutils:::.validate_generic_data_subset(data = data,
                                        subSet = subSet,
                                        target = target)

  if (!(weightsColumn %in% colnames(data))) {
    stop("Weights column is missing from data set.")
  }

  weights <- as.matrix(data[, get(weightsColumn)])[,1]
  vars <- as.matrix(data[, get(target)])[,1]

  #Re-escale weights
  weights <- (weights - 1) / (length(weights) - sum(1 / weights))
  #Calculate weighted average factor
  object$trainedModel <- list(factorMean = sum(weights * vars))
  #Set boolean trained flag
  object$isTrained <- TRUE
  return(object)
}

#' @rdname train
#' @export
train.strataHTModeler <- function(object, data, subSet = NULL) {
  target <- getTarget(object)
  weightsColumn <- object$weightsColumn

  #Validate target, subSet and filter data
  RMLutils:::.validate_target(object = object, data = data)
  data <- RMLutils:::.validate_generic_data_subset(data = data,
                                        subSet = subSet,
                                        target = target)
  if (!(weightsColumn %in% colnames(data))) {
    stop("Weights column is missing from data set.")
    }

  object$trainedModel$factorMeanStrata <- data[,
    sum(((get(weightsColumn) - 1) / (length(get(weightsColumn))
                                            - sum(1 / get(weightsColumn)))) * get(target)),
    by = eval(object$strata)]
  setnames(object$trainedModel$factorMeanStrata, "V1", target)

  object$trainedModel$factorMeanGeneral <- data[,
    sum(((get(weightsColumn) - 1) / (length(get(weightsColumn))
                                            - sum(1 / get(weightsColumn)))) * get(target))]
  #Set boolean trained flag
  object$isTrained <- TRUE
  return(object)
}

#' @rdname train
#' @importFrom stats weighted.mean
#' @export
train.strataMeanModeler <- function(object, data, subSet = NULL) {
  RMLutils:::.validate_target(object = object, data = data)
  data <- RMLutils:::.validate_generic_data_subset(data = data,
                                        subSet = subSet,
                                        target = object$target)
  #Check that regressors are categorical
  if(!all(sapply(data[, .SD, .SDcols = object$regressors],class) %in% c("character", "factor"))){
    stop("Some of the regressor variables are not categorical or characters.")
  }
  if (object$weightsColumn == "") {
    object$trainedModel$strata <- data[,
                              mean(get(object$target)),
                              by = eval(object$regressors)]
    setnames(object$trainedModel$strata, "V1", object$target)
    object$trainedModel$general <- data[,
                                        mean(get(object$target))]

  } else {
    object$trainedModel$strata <- data[,
                  weighted.mean(get(object$target), get(object$weightsColumn)),
                  by = eval(object$regressors)]
    setnames(object$trainedModel$strata, "V1", object$target)
    object$trainedModel$general <- data[,
                weighted.mean(get(object$target), get(object$weightsColumn))]
  }
  #Set boolean trained flag
  object$isTrained <- TRUE
  return(object)
}

#' @rdname train
#' @export
train.H2OModeler <- function(object, data, subSet = NULL) {
  movedData <- FALSE

  #TODO: Check that it works with H2OFrames (do the same with getPredictions)
  data <- RMLutils:::.validate_H2O_data_subset(data = data,
                                               subSet = subSet,
                                               target = object$target)
  RMLutils:::.validate_target_H2OModeler(object = object, data = data)

  if (!inherits(data, "H2OFrame")) {

    is.fact <- sapply(data, is.factor)
    for(nm in names(is.fact)){
      if(is.fact[nm]){
        data[, (nm) := factor(get(nm), ordered = FALSE)]
      }
    }
    #Check whether the target variable is categorical type and automatically set the class_names
    if(is.factor(data[[getTarget(object)]])){
      object$class_names <- levels(data[[getTarget(object)]])
    }

    data <- h2o::as.h2o(data)
    movedData <- TRUE
  }else{
    #Check whether the target variable is categorical type (enum) and automatically set the class_names
    if(h2o.getTypes(data[getTarget(object)])[[1]] == "enum"){
      object$class_names <- h2o::h2o.levels(data[[getTarget(object)]])
    }
  }

  arguments <- c(list(x = getRegressors(object), y = getTarget(object),
                        training_frame = data), object$params)
  object <- modelClean(object)
  object$trainedModel <- do.call(getFromNamespace(paste0("h2o.", object$model), "h2o"), arguments)
  if (movedData) h2o::h2o.rm(list(data))
  #Delete garbage from cloud
  current_cloud_elements <- as.character(h2o::h2o.ls()$key)
  h2o::h2o.rm(grep(pattern = "metrics", x = current_cloud_elements, value = TRUE))
  #Set boolean trained flag
  object$isTrained <- TRUE
  return(object)
}

#' @rdname train
#' @export
train.benchModeler <- function(object, data, subSet = NULL) {
  # Train submodels
  object$submodels <- lapply(
    object$submodels,
    train,
    data,
    subSet
  )

  # Optimization weights
  if (object$optWeights == "uniform") {
    w <- rep(1, length(object$target))

  } else if (object$optWeights == "MSE") {
    mse <- unlist(sapply(
      object$submodels,
      function(x) evaluate(x, data, MSECostFunction())
    ))
    w <- 1 / mse
  }

  # P matrix
  object$P <- Matrix::Diagonal(
    n = length(object$target),
    x = w
  )
  #Set boolean trained flag
  object$isTrained <- TRUE
  return(object)
}

