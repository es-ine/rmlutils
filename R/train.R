#' @title Trains a modeler object.
#'
#' @description Fits the model in the modeler generated by \code{\link{modeler}} container to the given data.
#'
#' @param object \code{\link{modeler}} object to fit to the data.
#' @param data Dataframe containing the data to use for the training
#' @param subSet Optional value, select a subSet of the data for the training.
#' @param val_data Optional value for catbostModeler objects. Used as validation set during training.
#'
#'
#' @return A trained modeler object, which contains some of the details and metrics
#' after training.
#'
#' @import data.table
#'
#' @examples
#' #Generate data
#' data.dt <- generateRegressionData(n_samples = 1000, generate_random_weights = FALSE)
#'
#' #Define train/test partitions
#' set.seed(273)
#' data.keys <- 1:nrow(data.dt)
#' train_size = round(0.8 * nrow(data.dt))
#' smplr <- srsSampler(key = data.keys, ssize = train_size)
#' train.keys <- getSample(smplr)
#' test.keys <- setdiff(data.keys, train.keys)
#'
#' #Define modeler
#' params <- list(
#'   "num.trees" = 50,
#'   "max.depth" = 20
#' )
#' target <- "regression_target"
#' regressors <- setdiff(colnames(data.dt), target)
#'
#' modeler <- rangerRegressorModeler(params = params, target = target, regressors = regressors)
#'
#' #Train modeler
#' modeler <- train(object = modeler, data = data.dt, subSet = train.keys)
#' @export
train <- function(object, data, subSet = NULL) {
  UseMethod("train")
}
